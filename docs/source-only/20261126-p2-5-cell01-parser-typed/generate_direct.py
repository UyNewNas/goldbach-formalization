#!/usr/bin/env python3
"""Quote the complete candidate AST using unchanged donor planning functions.

The generated original-reader equality, not this host program, is the proof.
Existing generated bytes are immutable; this program checks them on reruns.
"""
import argparse
import hashlib
import json
from pathlib import Path
from measure_input import load_input, MEASUREMENTS, immutable, checked_bytes

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
DONOR_SHA = '3114c68369ad3a6e3f7e3171aedadb40830917cf1592cc09e99932afdf71703d'
INPUT_SHA = 'd7215c408203fd149155ec34af91c0d3af45a49d4dc64e23b508917d176a5c2f'


def thin_transports(fuel, length):
    """Parameterize the existing two thin proofs without changing their proof steps."""
    candidates = []
    sources = [
        ('ImbalancedChen/P2Saving16Cell00SegmentedParse.lean',
         'a08f64469fc99999bfdec271b700cd9b566dbc897eaf2a4dc6ee1f95ea88e680'),
        ('docs/source-only/20261126-p2-5-cell00-decoded/ImbalancedChen/P2Saving16Cell00OriginalJson.lean',
         '3543baacddde3ff81b566b1f1c597251dd27d0981ba95161eeb25a8563ea3fda'),
    ]
    for relative, expected in sources:
        text = checked_bytes(REPO / relative, expected).decode()
        replacements = [
            ('ofList_chars00_eq_canonicalText0', 'ofList_chars01_eq_originalText1'),
            ('P2Saving16StringCharBinding00', 'P2Saving16CanonicalCell01Binding'),
            ('Cell00', 'Cell01'), ('cell00', 'cell01'), ('chars00', 'chars01'),
            ('(0 : Fin 14)', '(1 : Fin 14)'), ('53306', str(length + 1)),
            ('53305', str(length)), ('371', str(fuel)),
        ]
        applied = []
        for old, new in replacements:
            count = text.count(old)
            if count:
                text = text.replace(old, new)
                applied.append({'old': old, 'new': new, 'count': count})
        assert 'Cell00' not in text and 'cell00' not in text and 'chars00' not in text
        text = '/- SOURCE ONLY / UNCOMPILED. Cell01 instance of the unchanged thin proof pattern. -/\n' + text
        target = ROOT / 'ImbalancedChen' / Path(relative).name.replace('Cell00', 'Cell01')
        data = text.encode()
        immutable(target, data)
        candidates.append({'source': str(target.relative_to(REPO)), 'bytes': len(data),
                           'sha256': hashlib.sha256(data).hexdigest(),
                           'derived_from': {'path': relative, 'sha256': expected},
                           'parameter_substitutions': applied})
    return candidates

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True, help='Existing exact original Cell01 witness')
    args = parser.parse_args()
    raw, node, _, ns, _, measured = load_input(args.input)
    assert measured == json.loads(MEASUREMENTS.read_text())
    value=ns['lean_node'](node)
    text=r'''import ImbalancedChen.P2OriginalSaving19SourceJsonFuel
import ImbalancedChen.P2Saving16CanonicalCell01Binding

/-!
SOURCE ONLY / UNCOMPILED. Complete AST quoted by the unchanged P2.6 raw planner. Only the
original reader equality below can certify the quotation. All seventeen
fields, their order, every nested value, and the trailing CRLF are retained.
The parser, character input, and typed decoder are not changed.
-/
namespace ImbalancedChen.P2Saving16Cell01Segments
set_option maxRecDepth 1000000
set_option Elab.async false
set_option stderrAsMessages false
open P2OriginalSaving19Archive
open P2Saving16CanonicalCell01Binding (chars01)
noncomputable section

def rootValue : SourceJson :=
  '''+value+r'''

theorem cell01_valueFUEL :
    SourceJson.value FUEL chars01 = .ok (rootValue, TAIL) := by
  run_tac do
    Lean.Elab.Tactic.liftMetaFinishingTactic fun goal => do
      goal.refl (check := false)

#print axioms cell01_valueFUEL

end
end ImbalancedChen.P2Saving16Cell01Segments
'''
    text = text.replace('FUEL', str(node.need)).replace('TAIL', measured['parser']['tail_lean'])
    text=text.replace("'\\\\r'","'\\r'").replace("'\\\\n'","'\\n'")
    target=ROOT/'ImbalancedChen/P2Saving16Cell01DirectParse.lean'
    data=text.encode()
    immutable(target, data)
    direct = {'source': str(target.relative_to(REPO)), 'bytes': len(data),
              'sha256': hashlib.sha256(data).hexdigest()}
    manifest = {'schema': 'p25-cell01-original-parser-source-candidates-v1',
                'status': 'SOURCE_ONLY_UNCOMPILED', 'canonical_index': 1, 'input_sha256': INPUT_SHA,
                'input_bytes': len(raw), 'donor_sha256': DONOR_SHA, 'candidate_fuel': node.need,
                'tail_bytes': list(raw[node.end:]), 'value_end': node.end,
                'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                'measurement_sha256': hashlib.sha256(MEASUREMENTS.read_bytes()).hexdigest(),
                'sources': [direct, *thin_transports(node.need, len(raw))],
                'proof_credit_from_host': False, 'parse_proved': False, 'typed_decode_proved': False,
                'Lean_executed': False, 'Q96_proved': False, 'P2_5_proved': False}
    immutable(ROOT / 'PARSER_CANDIDATE_MANIFEST.json',
              (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode())
    print(json.dumps({key: manifest[key] for key in ['status', 'candidate_fuel', 'sources', 'proof_credit_from_host']}))

if __name__=='__main__': main()
