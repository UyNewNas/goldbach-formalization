#!/usr/bin/env python3
"""Quote the complete candidate AST using unchanged donor planning functions.

The generated original-reader equality, not this host program, is the proof.
Existing generated bytes are immutable; this program checks them on reruns.
"""
import ast
import dataclasses
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
DONOR_SHA = '3114c68369ad3a6e3f7e3171aedadb40830917cf1592cc09e99932afdf71703d'
INPUT_SHA = '360a9ef6bbe76fe38fc8146a16e821f43ade93e9e41911bc3a2dfd8b49067ee6'

def main():
    donor=(ROOT/'donor/generate.py').read_bytes()
    assert hashlib.sha256(donor).hexdigest()==DONOR_SHA
    names={'Node','Field','RawPlanner','quote_char','quote_list','lean_node'}
    body=[n for n in ast.parse(donor).body if isinstance(n,(ast.ClassDef,ast.FunctionDef)) and n.name in names]
    ns={'dataclass':dataclasses.dataclass,'field':dataclasses.field,'WHITE':b' \r\n\t','__name__':'__main__'}
    exec(compile(ast.Module(body=body,type_ignores=[]),'<unchanged donor AST quotation>','exec'),ns)
    raw=(REPO/'.lake/p25-original-inputs/eighth-prefix-family-20261009-cell-00.witness.json').read_bytes()
    assert len(raw)==53305 and hashlib.sha256(raw).hexdigest()==INPUT_SHA
    node=ns['RawPlanner'](raw).value(0)
    assert node.need==371 and raw[node.end:]==b'\r\n'
    value=ns['lean_node'](node)
    text=r'''import ImbalancedChen.P2OriginalSaving19SourceJsonFuel
import ImbalancedChen.P2Saving16StringCharBinding00

/-!
Candidate complete AST quoted by the unchanged P2.6 raw planner. Only the
original reader equality below can certify the quotation. All seventeen
fields, their order, every nested value, and the trailing CRLF are retained.
The parser, character input, and typed decoder are not changed.
-/
namespace ImbalancedChen.P2Saving16Cell00Segments
set_option maxRecDepth 1000000
set_option Elab.async false
set_option stderrAsMessages false
open P2OriginalSaving19Archive
open P2Saving16StringCharBinding00 (chars00)
noncomputable section

def rootValue : SourceJson :=
  '''+value+r'''

theorem cell00_value371 :
    SourceJson.value 371 chars00 = .ok (rootValue, ['\r', '\n']) := by
  run_tac do
    Lean.Elab.Tactic.liftMetaFinishingTactic fun goal => do
      goal.refl (check := false)

#print axioms cell00_value371

end
end ImbalancedChen.P2Saving16Cell00Segments
'''
    text=text.replace("'\\\\r'","'\\r'").replace("'\\\\n'","'\\n'")
    target=ROOT/'ImbalancedChen/P2Saving16Cell00DirectParse.lean'
    data=text.encode()
    if target.exists():
        assert target.read_bytes()==data, 'Generated source drift; preserve old attempt before explicit revision.'
    else:
        target.write_bytes(data)
    print(json.dumps({'source':str(target),'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),
                      'input_sha256':INPUT_SHA,'donor_sha256':DONOR_SHA,'candidate_fuel':371,
                      'proof_credit_from_host':False}))

if __name__=='__main__': main()
