import argparse
import hashlib
import json
import re
import subprocess

HERE = Path(__file__).resolve().parent
DIAGNOSTICS = HERE / 'diagnostics'
PREFIX = 'ImbalancedChen.P2OriginalSaving19HigherMoments'
OWNERS = [
    'ImbalancedChen.P2OriginalSaving19MomentAntidiagonalSplit',
    PREFIX + 'NewtonStructure',
    PREFIX + 'MomentStructure',
]
FROZEN = {
    PREFIX + 'Core': '3738b75a69892c1f9ab68a395b6394817e24a94083ca5254b38c32d73a859832',
    PREFIX + 'GuardLowBoundary': '3fa7f12eb715a9aabac0c431533fbb515ad3d2512aadd8eec677c5b098486604',
    'ImbalancedChen.P2OriginalSaving19MomentFiniteReindex': 'ef69493b03eea3c013fe645f20f5a70b4348e64ec3c59aef1a0e325afa42e902',
    PREFIX + 'Symmetry': '5425985922dae867d1a1be2903c2def751187894373d700ca3a8a62b3346e16d',
    PREFIX + 'SymmetryPilot': '8cd95f3227fcbdd2172eb19df40f2553e53c34b375d45c80e20d444a131d3902',
}
DIAGNOSTIC_SHAS = {
    'NewtonSmallDiagnostic': '57de3ce2798f5217fc402cb395453bc145bb04bd4643994e73053eda59976e8b',
    'NewtonDuplicateDiagnostic': 'e550fad6b49131894edb813855e57c05a33bc4b51df59b8f1c28b7627bbb8d9b',
    'FiniteSplitDiagnostic': 'b5af563b97a60b8970cfd30da55c640a88f7a927bc4b537a1f556ee4a4f1cf5d',
    'AntidiagonalCompleteDiagnostic': '1a8e47c125d5fd666e2443125b55ea043c546dc0981878d687e66909e4eaf98a',
    'FactoredGuardDiagnostic': '67ae48cb337dd24f762e6d157643d9da2874c85d9480eed1f6bf0f617fa6d751',
}

def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def module_path(module: str) -> str:
    return module.replace('.', '/') + '.lean'

def between(text: str, start: str, end: str) -> str:
    return text[text.index(start):text.index(end, text.index(start))].rstrip() + '\n'

def write_or_check(path: Path, text: str, check: bool) -> None:
    data = text.encode()
    if check:
        assert path.read_bytes() == data, 'Generated bytes differ: ' + str(path)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)

parser = argparse.ArgumentParser()
parser.add_argument('--source-root', type=Path, default=Path('/workspace/p26-source-closure'))
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source_root = args.source_root.resolve()
base = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=source_root, text=True).strip()

def git_source(path: str) -> bytes:
    return subprocess.check_output(['git', 'show', base + ':' + path], cwd=source_root)

diag, diagnostic_receipts = {}, {}
for module, digest in DIAGNOSTIC_SHAS.items():
    p = DIAGNOSTICS / (module + '.lean')
    data = p.read_bytes()
    assert sha(data) == digest, module
    diag[module] = data.decode()
    receipt_path = DIAGNOSTICS / (module + '.json')
    receipt = json.loads(receipt_path.read_text())
    assert receipt['exit_code'] == 0 and receipt['source_sha256'] == digest
    log = DIAGNOSTICS / (module + '.log')
    assert sha(log.read_bytes()) == receipt['log_sha256']
    assert 'sorryAx' not in log.read_text()
    diagnostic_receipts[module] = {
        'source_path': str(p), 'source_sha256': digest,
        'receipt_path': str(receipt_path), 'receipt_sha256': sha(receipt_path.read_bytes()),
        'log_path': str(log), 'log_sha256': sha(log.read_bytes()),
        'normal_seconds': receipt['seconds'], 'peak_child_rss_kib': receipt['peak_child_rss_kib'],
        'status': 'LOCAL_COPIED_CORE_DIAGNOSTIC_ONLY_NOT_PRODUCTION_ACCEPTANCE',
    }

core_bytes = git_source(module_path(PREFIX + 'Core'))
assert sha(core_bytes) == FROZEN[PREFIX + 'Core']
core = core_bytes.decode()
core_factored = core.split('theorem integratedPower_eq_factored', 1)[1].split('integratedPower y i k =\n', 1)[1].split(' := by', 1)[0]
diag_factored = diag['FactoredGuardDiagnostic'].split('def factoredIntegratedPower', 1)[1].split(' :=\n', 1)[1].split('\n\ntheorem ', 1)[0]
assert core_factored == diag_factored, 'Copied factored RHS changed'

namespace = 'namespace ' + PREFIX + '.ProofPieces\nnoncomputable section\nopen scoped BigOperators\n\n'
end = '\nend\nend ' + PREFIX + '.ProofPieces\n'
header = '/-! SOURCE CANDIDATE: pending production normal/kernel/full-owned acceptance.\nThe manuscript simplex-moment formula and existing Core definitions are retained.\nOnly finite sum reindexing and bounded Newton algebra are reorganized.\nNo finite exponent-vector list is enumerated; no tactic budget is increased. -/\n'

split_body = between(diag['FiniteSplitDiagnostic'], 'theorem sum_piAntidiag_univ_fin_succ', '\nend P26LocalMomentStructural')
split_source = ('import Mathlib.Algebra.Order.Antidiag.Pi\n'
                'import Mathlib.Algebra.BigOperators.Fin\n'
                'import Mathlib.Algebra.BigOperators.Group.Finset.Sigma\n'
                'import Lean.Elab.Tactic.Omega\n\n' + header + namespace + split_body + end)

newton_body = between(diag['NewtonSmallDiagnostic'], 'def powerSum ', '\nend\nend P26LocalMomentStructural')
newton_body += '\n' + between(diag['NewtonDuplicateDiagnostic'], 'theorem duplicateH_eq_completeH_small', '\ntheorem duplicateH_author_guard_6_structural')
newton_body += '\n' + between(diag['FactoredGuardDiagnostic'], 'theorem duplicateH_author_guard_structural', '\nend\nend P26LocalMomentStructural')
newton_source = 'import ' + PREFIX + 'Core\n\n' + header + namespace + newton_body + end

antidiagonal_body = between(diag['AntidiagonalCompleteDiagnostic'], 'theorem completeH_ofFn_eq_antidiagonal', '\nend\nend P26LocalMomentStructural')
zero_guard = between(diag['FactoredGuardDiagnostic'], 'theorem factoredIntegratedPower_newton_guard_zero', '\ntheorem duplicateH_author_guard_structural')
zero_guard = zero_guard.replace('factoredIntegratedPower_newton_guard_zero', 'integratedPower_newton_guard_zero_structural')
zero_guard = zero_guard.replace('factoredIntegratedPower y 0 k', 'integratedPower y 0 k')
zero_guard = zero_guard.replace('rw [factoredIntegratedPower,', 'rw [integratedPower_eq_factored,')
all_indices = """theorem integratedPower_newton_guard_structural (y : Fin 9 → ℝ)
    (i : Fin 9) (k : ℕ) (hk : k ≤ 6) :
    integratedPower y i k =
      duplicateH y i k / ((Nat.factorial 9 : ℝ) * ((9 + k).choose k : ℝ)) := by
  simpa only [integratedPower_perm, duplicateH_perm, Equiv.swap_apply_left] using
    integratedPower_newton_guard_zero_structural (y ∘ Equiv.swap (0 : Fin 9) i) k hk
"""
moment_source = ('import ' + OWNERS[0] + '\n'
                 'import ' + OWNERS[1] + '\n'
                 'import ' + PREFIX + 'Symmetry\n\n'
                 + header + namespace + antidiagonal_body + '\n' + zero_guard
                 + '\n' + all_indices + end)

generated = dict(zip(OWNERS, [split_source, newton_source, moment_source]))
for module, text in generated.items():
    assert not re.search(r'\b(sorry|admit|native_decide|unsafe)\b|^axiom\s', text, re.M)
    assert 'set_option' not in text
    assert 'antidiagonalTuple' not in text
    write_or_check(HERE / module_path(module), text, args.check)

modules, inputs, graph, active = {}, {}, {}, []
def visit(module: str) -> None:
    assert module not in active, 'Import cycle: ' + module
    if module in inputs:
        return
    path = module_path(module)
    owned = module in OWNERS
    source = HERE / path if owned else source_root / path
    data = source.read_bytes() if owned else git_source(path)
    if not owned:
        assert source.read_bytes() == data, 'Working source differs from Git base: ' + module
    imports = [m.strip() for m in re.findall(r'^import (.+)$', data.decode(), re.M)]
    digest = sha(data)
    if module in FROZEN:
        assert digest == FROZEN[module]
    row = {'path': path, 'sha256': digest, 'bytes': len(data), 'imports': imports}
    inputs[module] = {**row, 'local_source_path': str(source),
        'origin_kind': 'NEW_STRUCTURAL_OWNER' if owned else 'UNCHANGED_COHERENT_BASE',
        'observed_base_commit': None if owned else base}
    if owned:
        modules[module] = {**row, 'local_source_path': str(source),
            'status': 'SOURCE_CANDIDATE_PENDING_P1_NORMAL_KERNEL_FULL_OWNED'}
    graph[module] = [m for m in imports if m.startswith('ImbalancedChen.')]
    active.append(module)
    for dep in graph[module]:
        visit(dep)
    active.pop()

for owner in OWNERS:
    visit(owner)
assert set(modules) == set(OWNERS)
assert PREFIX not in inputs
assert not any(re.search(r'HigherMoments(?:GuardK[0-6]I|AuthorK[0-6])', m) for m in inputs)

frozen_rows = {}
for module, digest in FROZEN.items():
    path = module_path(module)
    data = git_source(path)
    assert sha(data) == digest
    assert (source_root / path).read_bytes() == data
    frozen_rows[module] = {'path': path, 'sha256': digest, 'bytes': len(data),
        'local_source_path': str(source_root / path), 'observed_base_commit': base,
        'is_in_new_owner_import_closure': module in inputs}

def closure(module: str) -> list[str]:
    seen, pending = set(), [module]
    while pending:
        m = pending.pop()
        if m not in seen:
            seen.add(m)
            pending.extend(graph[m])
    return sorted(seen)

closures = {m: closure(m) for m in OWNERS}
input_payload = {
    'schema': 'p26_structural_moments_source_inputs_v1',
    'status': 'STATIC_SOURCE_BINDING_ONLY_NO_P1_ACCEPTANCE',
    'observed_base_source_commit': base,
    'new_owner_order': OWNERS,
    'project_sources': inputs,
    'project_import_graph': graph,
    'source_closures': closures,
    'all_base_sources_match_observed_git_commit': True,
    'all_new_owners_are_unpublished_candidates_at_manifest_generation': True,
}
inputs_path = HERE / 'STRUCTURAL_SOURCE_INPUTS.json'
write_or_check(inputs_path, json.dumps(input_payload, indent=2) + '\n', args.check)
manifest = {
    'schema': 'p26_structural_moments_three_owner_manifest_v1',
    'status': 'READY_FOR_PARENT_P1_SOURCE_PUBLICATION_NOT_ACCEPTED',
    'baseline_sha256': '59ccbb110e9aceac63a5bb7030b49e0f1103993bc6b2f6fb2b49a80391b2d41e',
    'owner_count': len(OWNERS),
    'recommended_first_order': OWNERS,
    'modules': {m: modules[m] for m in OWNERS},
    'retained_accepted_source_bindings': frozen_rows,
    'retained_acceptance_basis': 'Parent-reported P1 Core/Low acceptance and job083d370ffa89406493c44b29934a4413 three-owner Symmetry acceptance; this manifest verifies frozen source bytes only.',
    'observed_base_source_commit': base,
    'source_inputs': {'path': str(inputs_path), 'sha256': sha(inputs_path.read_bytes())},
    'source_closure_counts': {m: len(c) for m, c in closures.items()},
    'source_configuration': {p: {'sha256': sha(git_source(p)), 'bytes': len(git_source(p))}
        for p in ['lean-toolchain', 'lake-manifest.json', 'lakefile.toml']},
    'local_diagnostics': diagnostic_receipts,
    'exact_core_factored_rhs_sha256': sha(core_factored.encode()),
    'diagnostic_limit': 'Finite split and copied-Core structural proofs were locally checked. Actual production owner imports/full-owned audit were not run. The all-index final wrapper reuses the already accepted Symmetry/Pilot proof pattern.',
    'source_proof_scope': 'Existing Fin9 and k<=6 identities; generic helper statements only rearrange finite sums and the existing completeH definition.',
    'paper_boundary': 'The appendix explicitly supplies the simplex barycentric moment formula; the bounded Newton and duplicate-node identities here are proved finite algebraic derivations, not quotations of an explicit appendix Newton theorem.',
    'explicitly_out_of_scope': [PREFIX, 'Any old enumerated GuardK/AuthorK provider compile', 'Archive payloads or parser changes'],
    'production_facade_changed': False,
    'old_suppliers_recompiled_by_this_work': False,
    'new_structural_owners_remote_compiled_by_this_work': False,
    'global_or_tactic_budget_increases_in_new_owners': [],
    'parent_runner_requirement': 'Use a new three-owner scope and bind all input sources to the new published commit. Reuse existing normal/kernel/full-owned machinery; do not rerun the frozen accepted Core/Low/Symmetry owners.',
}
write_or_check(HERE / 'STRUCTURAL_SOURCE_MANIFEST.json', json.dumps(manifest, indent=2) + '\n', args.check)
