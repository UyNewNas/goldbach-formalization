#!/usr/bin/env python3
"""Parameterized original-reader pilots directly on production packed inputs.

Candidate generation is not proof. Every emitted claim must receive the fixed
normal/kernel checks. Cell00 is deliberately excluded because it is frozen.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import raw_planner as base
import fragment_templates as fragments

ROOT = Path(__file__).resolve().parent
V4 = ROOT.parent / 'archive-v4'
ACCEPTED = ROOT.parent / 'geometry-packed-transport'
OWNER_RAW_BUDGET = 4096
CHUNK_RAW_BUDGET = 768
MAX_CHUNKS = 4


def fp(path):
    path = Path(path); data = path.read_bytes()
    return {'path': str(path), 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def write_new(path, data):
    path = Path(path); data = data.encode() if isinstance(data, str) else data
    if path.exists():
        assert path.read_bytes() == data, ('Frozen candidate drift', str(path))
    else:
        path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(data)


def marker(label):
    return ('run_cmd do\n  let err ← IO.getStderr\n'
            f'  err.putStrLn "P26_DIRECT_PACKED {label}"\n  err.flush\n\n')


class Engine:
    def __init__(self, cell, raw_path, work):
        assert 1 <= cell <= 12, 'Cell00 is frozen and cannot be regenerated by this tool.'
        self.cell = cell; self.work = Path(work).resolve(); self.project = self.work / 'project'
        self.ns = f'ImbalancedChen.P2OriginalSaving19Geometry{cell:02d}DirectParsing'
        self.tag = f'P2OriginalSaving19Geometry{cell:02d}Direct'
        all_paths = json.loads((V4 / 'INPUT_PATHS.json').read_text())
        self.expected = next(row for row in all_paths['paths'] if row['family'] == 'geometry' and row['cell'] == cell)
        self.raw_origin = Path(raw_path).resolve(); self.raw = self.raw_origin.read_bytes()
        assert len(self.raw) == self.expected['bytes'] and base.sha(self.raw) == self.expected['sha256']
        assert self.raw.isascii(), 'Byte/Char offset planner requires verified ASCII; no silent Unicode reindexing.'
        self.fixture = self.work / 'goldbach-research' / Path(self.expected['loader_relative_path']).name
        write_new(self.fixture, self.raw)
        self.node = base.RawPlanner(self.raw).value(0)
        assert self.node.kind == 'obj' and self.node.start == 0
        assert all(c in base.WHITE for c in self.raw[self.node.end:])
        keys = [f.key.scalar for f in self.node.fields]
        assert len(set(keys)) == len(keys), 'Do not hide original duplicate keys through a host dictionary.'
        self.fields = {f.key.scalar: f for f in self.node.fields}
        for path in [self.project / 'ImbalancedChen', self.work / 'objects/ImbalancedChen', self.work / 'owners', self.work / 'logs']:
            path.mkdir(parents=True, exist_ok=True)
        self.prepare_frozen()
        self.bootstrap(all_paths)
        fragments.configure(cell, self.raw, self.chunks_for)

    def prepare_frozen(self):
        accepted = json.loads((ACCEPTED / 'SOURCE_INPUTS.json').read_text())['inputs']
        catalog = {row['module']: row for row in accepted}
        wanted = ['ImbalancedChen.' + short for short in [
            'P2OriginalSaving19ArchivePackedLoader', 'P2OriginalSaving19ParseFromValue00']]
        seen = set(); ordered = []
        def visit(module):
            if module in seen:
                return
            seen.add(module); row = catalog[module]
            assert fp(row['source']['path']) == row['source'] and fp(row['object']['path']) == row['object']
            assert not any(x in module for x in ['CharacterCore', 'WholeValue', 'WholeParse', 'GeometryPackedTransport'])
            for dep in row['project_imports']:
                visit(dep)
            ordered.append({k: row[k] for k in ['module', 'source', 'object', 'project_imports']})
        for module in wanted:
            visit(module)
        assert len(ordered) == 6
        write_new(self.work / 'FROZEN_SUPPLIERS.json', json.dumps({'inputs': ordered,
                  'accepted_manifest': fp(ACCEPTED / 'SOURCE_MANIFEST.json'),
                  'no_cell00_geometry_input_imported': True, 'recompiled': False}, indent=2) + '\n')
        write_new(self.work / 'run_owner.py', (ACCEPTED / 'run_owner.py').read_bytes())

    def bootstrap(self, all_paths):
        original = V4 / self.expected['relative_source']
        assert fp(original) == self.expected['candidate_source']
        copied = self.project / self.expected['relative_source']
        write_new(copied, original.read_bytes())
        record = {'cell': self.cell, 'input_original': fp(self.raw_origin), 'input_private_copy': fp(self.fixture),
                  'expected_original_input': self.expected, 'metadata_provenance': all_paths['source_evidence'],
                  'data_source_original': fp(original), 'data_source_copy': fp(copied),
                  'lean_working_directory': str(self.project),
                  'actual_resolved_input_path': str((self.project / self.expected['loader_relative_path']).resolve()),
                  'same_v4_source_bytes': True, 'ASCII_byte_equals_Char_offsets_verified': True,
                  'production_modified': False, 'remote_jobs_submitted': False,
                  'all13_pass_claimed': False, 'cell00_reparsed': False,
                  'template_provenance': fp(ROOT / 'TEMPLATE_PROVENANCE.json')}
        write_new(self.work / 'BOOTSTRAP.json', json.dumps(record, indent=2) + '\n')
        plan = {'cell': self.cell, 'full_input_bytes': len(self.raw), 'root_value_span': [0, self.node.end],
                'root_value_candidate_fuel_offset': self.node.need, 'original_parse_fuel': len(self.raw) + 1,
                'exact_tail_hex': self.raw[self.node.end:].hex(),
                'fields': [{'key': f.key.scalar, 'prefix_span': [f.prefix_start, f.prefix_end],
                            'value_span': [f.value.start, f.value.end], 'kind': f.value.kind,
                            'array_items': len(f.value.children) if f.value.kind == 'arr' else None}
                           for f in self.node.fields],
                'candidate_only_not_reader_acceptance': True}
        write_new(self.work / 'RAW_PLAN.json', json.dumps(plan, indent=2) + '\n')

    def registry(self):
        rows = {x['module']: x for x in json.loads((self.work / 'FROZEN_SUPPLIERS.json').read_text())['inputs']}
        for path in (self.work / 'owners').glob('*.json'):
            m = json.loads(path.read_text())
            rows[m['module']] = {'module': m['module'], 'source': m['source'], 'project_imports': m['project_imports'],
                'object': {'path': str(self.work / 'objects' / (m['module'].replace('.', '/') + '.olean'))}}
        return rows

    def save(self, short, text, scope, plan):
        text = text.replace('\ndef ', '\nnoncomputable def ')
        path = self.project / 'ImbalancedChen' / (short + '.lean'); write_new(path, text)
        imports = re.findall(r'(?m)^import\s+(ImbalancedChen\.\S+)', text)
        known = self.registry(); seen = set(); closure = []
        def visit(module):
            if module in seen:
                return
            seen.add(module); row = known[module]
            assert fp(row['source']['path']) == row['source']
            for name in row['project_imports']:
                visit(name)
            closure.append(row)
        for module in imports:
            visit(module)
        record = {'module': 'ImbalancedChen.' + short, 'source': fp(path), 'scope': scope,
                  'project_imports': imports, 'dependency_closure': closure, 'fixture': fp(self.fixture),
                  'planned_obligations': plan, 'production_input_FQN': self.expected['definition'],
                  'whole_cell_parse_claimed': False, 'all13_pass_claimed': False,
                  'host_plan_is_proof': False, 'production_modified': False,
                  'remote_jobs_submitted': False, 'accepted_dependencies_recompiled': False}
        write_new(self.work / 'owners' / (short + '.json'), json.dumps(record, indent=2) + '\n')
        return record

    def head(self, imports, text):
        return ''.join('import ' + x + '\n' for x in imports) + f'''
/-! {text}
Original-reader equations and exact production packed-input slices are checked
in Lean. No whole-cell parse or typed decoding claim is made by this pilot. -/
namespace {self.ns}
set_option maxRecDepth 1000000
set_option Elab.async false
set_option stderrAsMessages false
open ImbalancedChen.P2OriginalSaving19Archive
open ImbalancedChen.P2OriginalSaving19PackedChars

'''

    def foot(self, names, nested=None):
        ending = ('\n\nend ' + nested if nested else '') + '\n\nend ' + self.ns + '\n'
        return '\n'.join('#print axioms ' + n for n in names) + ending

    def emit_split(self, name, start, end, chars):
        return f'''theorem {name}_prefix :
    (sourceRest {start}).take {end-start} = {chars} := by rfl

theorem {name}_split : sourceRest {start} = {chars} ++ sourceRest {end} := by
  calc
    sourceRest {start} = (sourceRest {start}).take {end-start} ++ (sourceRest {start}).drop {end-start} :=
      (List.take_append_drop {end-start} (sourceRest {start})).symm
    _ = {chars} ++ (sourceRest {start}).drop {end-start} :=
      congrArg (fun part => part ++ (sourceRest {start}).drop {end-start}) {name}_prefix
    _ = {chars} ++ sourceRest {end} :=
      congrArg (fun tail => {chars} ++ tail) (sourceRest_drop {start} {end-start})

'''

    def data_owner(self):
        short = self.expected['module'].split('.')[-1]
        text = (self.project / self.expected['relative_source']).read_text()
        return self.save(short, text, 'Exact unchanged production packed-data source in private mirror',
                         {'data_only': True, 'same_v4_source_bytes': True})

    def input_owner(self):
        short = self.tag + 'Input'
        text = self.head([self.expected['module'], 'ImbalancedChen.P2OriginalSaving19ParseFromValue00'],
                         f'Cell {self.cell:02d}: direct packed input and exact remaining-list interfaces.')
        packed = f'geometryPacked{self.cell:02d}'; size = len(self.raw)
        text += f'''def sourceChars : List Char := {packed}.toList
def sourceRest (n : Nat) : List Char := ({packed}.drop n).toList

theorem sourceRest_eq_drop (n : Nat) : sourceRest n = sourceChars.drop n :=
  Tree.toList_drop {packed} n

theorem sourceRest_drop (start count : Nat) :
    (sourceRest start).drop count = sourceRest (start + count) := by
  simp only [sourceRest_eq_drop, List.drop_drop]

theorem sourceRest_zero : sourceRest 0 = sourceChars := by
  simpa only [List.drop_zero] using sourceRest_eq_drop 0

theorem sourcePacked_count : {packed}.count = {size} := by decide +kernel

theorem sourceChars_length : sourceChars.length = {size} :=
  (Tree.length_toList {packed}).trans sourcePacked_count

theorem sourceRest_end : sourceRest {size} = [] := by
  rw [sourceRest_eq_drop]
  exact List.drop_eq_nil_of_le (by rw [sourceChars_length]; exact Nat.le_refl _)

'''
        text += self.foot(['sourceRest_eq_drop', 'sourceRest_drop', 'sourceRest_zero',
                           'sourcePacked_count', 'sourceChars_length', 'sourceRest_end'])
        return self.save(short, text, 'Exact input interfaces; only tree count uses kernel decide',
                         {'full_character_count': size, 'full_parse_proved': False})

    def metadata_owner(self, count=5):
        assert 0 < count < len(self.node.fields)
        fields = self.node.fields[:count]; end = fields[-1].prefix_end
        assert all(f.separator == ',' for f in fields)
        assert end <= OWNER_RAW_BUDGET, 'Metadata prefix exceeds measured grouping policy; partition explicitly.'
        offset = max(i + 2 + max(f.key.quoted_need, f.value.need) for i, f in enumerate(fields))
        after = offset - 1 - count; assert after >= 0
        actual = len(self.raw) + 1; assert actual >= offset
        acc = '[' + ', '.join('(String.ofList ' + base.quote_list(f.key.scalar) + ', ' + base.lean_node(f.value) + ')'
                              for f in reversed(fields)) + ']'
        short = self.tag + f'Metadata{count:02d}'
        text = self.head(['ImbalancedChen.' + self.tag + 'Input'], f'First {count} original fields grouped without dropping duplicate-key checks.')
        nested = f'Metadata{count:02d}'
        text += 'namespace ' + nested + '\n\n'
        text += f'''def metadataChars : List Char := {base.chars(self.raw,0,end)}
def metadataAcc : List (String × SourceJson) := {acc}

theorem value_metadata (fuel : Nat) (tail : List Char) :
    SourceJson.value (fuel + {offset}) (metadataChars ++ tail) =
      SourceJson.object (fuel + {after}) (SourceJson.white tail) metadataAcc := by rfl

'''
        text += marker('metadata_before_packed_binding') + self.emit_split('metadata_original', 0, end, 'metadataChars')
        text += f'''theorem sourceChars_metadata_split : sourceChars = metadataChars ++ sourceRest {end} :=
  sourceRest_zero.symm.trans metadata_original_split

theorem sourceChars_through_metadata :
    SourceJson.value {actual} sourceChars =
      SourceJson.object {actual-1-count} (SourceJson.white (sourceRest {end})) metadataAcc :=
  (congrArg (SourceJson.value {actual}) sourceChars_metadata_split).trans
    (value_metadata {actual-offset} (sourceRest {end}))

'''
        text += self.foot(['value_metadata', 'metadata_original_prefix', 'metadata_original_split',
                           'sourceChars_metadata_split', 'sourceChars_through_metadata'], nested)
        return self.save(short, text, 'Actual original reader through a grouped root metadata prefix',
                         {'field_count': count, 'original_keys': [f.key.scalar for f in fields],
                          'raw_span': [0, end], 'generic_value_fuel_offset': offset,
                          'actual_original_value_fuel': actual, 'post_object_fuel': actual-1-count})

    def chunks_for(self, node, max_items=2, max_bytes=CHUNK_RAW_BUDGET):
        assert node.kind == 'arr' and node.children
        chunks = []; first = 0; start = node.start + 1
        while first < len(node.children):
            after = first
            while after < len(node.children) and after - first < max_items:
                candidate = after + 1; final = candidate == len(node.children)
                end = node.end if final else node.children[candidate - 1].end
                if not final:
                    while self.raw[end] in base.WHITE:
                        end += 1
                    assert self.raw[end] == ord(','); end += 1
                if end - start > max_bytes and after > first:
                    break
                after = candidate
                if end - start >= max_bytes:
                    break
            final = after == len(node.children)
            end = node.end if final else node.children[after - 1].end
            if not final:
                while self.raw[end] in base.WHITE:
                    end += 1
                assert self.raw[end] == ord(','); end += 1
            chunks.append({'index': len(chunks), 'first': first, 'after': after, 'start': start, 'end': end,
                           'final': final, 'before_offset': node.need-1-first, 'after_offset': node.need-1-after,
                           'inline_bytes': end-start, 'oversize_child': end-start > max_bytes})
            first = after; start = end
        return chunks

    def block_plan(self, key):
        node = self.fields[key].value; chunks = self.chunks_for(node)
        groups = []; group = []
        for chunk in chunks:
            if group and (len(group) == MAX_CHUNKS or chunk['end'] - group[0]['start'] > OWNER_RAW_BUDGET):
                groups.append(group); group = []
            group.append(chunk)
        if group:
            groups.append(group)
        return node, groups

    def array_block_owner(self, key, index=0):
        node, groups = self.block_plan(key); selected = groups[index]
        assert selected[-1]['end']-selected[0]['start'] <= OWNER_RAW_BUDGET, ('Selected nested child needs a separate grouped supplier', key, index)
        tag = ''.join(part.title() for part in key.split('_'))
        assert re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', tag)
        short = self.tag + tag + f'Block{index:03d}'
        text = self.head(['ImbalancedChen.' + self.tag + 'Input'],
                         f'Original {key} grouped chunk transitions, including exact compact-input binding.')
        nested = tag + f'Block{index:03d}'
        text += 'namespace ' + nested + '\n\n'
        names = []; emitted = set(); literals = 0
        def inline_fragment(child):
            nonlocal text, literals
            if child.start in emitted:
                return
            for descendant in fragments.children_to_certify(child):
                inline_fragment(descendant)
            if not fragments.needs_ref(child) or child.kind not in ['arr', 'obj']:
                body, proofs = fragments.emit_small(child)
            elif child.kind == 'arr':
                body, proofs = fragments.emit_array(child)
            else:
                body, proofs = fragments.emit_object(child)
            emitted.add(child.start); text += body; names.extend(proofs)
        for chunk in selected:
            if chunk['oversize_child']:
                assert chunk['after'] == chunk['first'] + 1
                inline_fragment(node.children[chunk['first']])
        char_names = []; push = 'acc'
        for local, chunk in enumerate(selected):
            name = f'chunk{chunk["index"]:04d}'; theorem = f'array_{name}'
            body, extra = fragments.array_segment(name, theorem, chunk['start'], chunk['end'],
                node.children[chunk['first']:chunk['after']], chunk['before_offset'], chunk['after_offset'], chunk['final'])
            text += marker(name + '_before_reader') + body + marker(name + '_reader_complete')
            names += extra + [theorem]; char_names.append(name + 'Chars00'); push = f'{name}Push00 ({push})'
        first = selected[0]; last = selected[-1]
        chars = fragments.append_chain(char_names); payload = fragments.append_chain(char_names, 'tail')
        rhs = ('.ok (.arr ((blockPush acc).reverse), tail)' if last['final'] else
               f'SourceJson.array (fuel + {last["after_offset"]}) (SourceJson.white tail) (blockPush acc)')
        text += f'''def blockChars : List Char := {chars}
def blockPush (acc : List SourceJson) : List SourceJson := {push}

theorem array_block (fuel : Nat) (tail : List Char) (acc : List SourceJson) :
    SourceJson.array (fuel + {first['before_offset']}) (SourceJson.white (blockChars ++ tail)) acc =
      {rhs} := by
  have hinput : blockChars ++ tail = {payload} := by simp only [blockChars, List.append_assoc]
  calc
    SourceJson.array (fuel + {first['before_offset']}) (SourceJson.white (blockChars ++ tail)) acc =
        SourceJson.array (fuel + {first['before_offset']}) (SourceJson.white ({payload})) acc :=
      congrArg (fun chars => SourceJson.array (fuel + {first['before_offset']}) (SourceJson.white chars) acc) hinput
'''
        acc = 'acc'
        for i, chunk in enumerate(selected):
            rest = fragments.append_chain(char_names[i+1:], 'tail') if i+1 < len(selected) else 'tail'
            next_acc = f'chunk{chunk["index"]:04d}Push00 ({acc})'
            target = rhs if i+1 == len(selected) else f'SourceJson.array (fuel + {chunk["after_offset"]}) (SourceJson.white ({rest})) ({next_acc})'
            text += f'    _ = {target} := array_chunk{chunk["index"]:04d} fuel ({rest}) ({acc})\n'
            acc = next_acc
        text += '\n' + marker('block_before_packed_binding')
        text += self.emit_split('block_original', first['start'], last['end'], 'blockChars')
        actual_rhs = (f'.ok (.arr ((blockPush acc).reverse), sourceRest {last["end"]})' if last['final'] else
            f'SourceJson.array (fuel + {last["after_offset"]}) (SourceJson.white (sourceRest {last["end"]})) (blockPush acc)')
        text += f'''theorem array_block_original (fuel : Nat) (acc : List SourceJson) :
    SourceJson.array (fuel + {first['before_offset']}) (SourceJson.white (sourceRest {first['start']})) acc =
      {actual_rhs} :=
  (congrArg (fun chars => SourceJson.array (fuel + {first['before_offset']}) (SourceJson.white chars) acc)
    block_original_split).trans (array_block fuel (sourceRest {last['end']}) acc)

'''
        names += ['array_block', 'block_original_prefix', 'block_original_split', 'array_block_original']
        text += self.foot(names, nested)
        return self.save(short, text, 'Grouped actual array-reader transition with arbitrary tail and accumulator',
                         {'key': key, 'block': index, 'planned_block_count': len(groups),
                          'selected_chunks': selected, 'raw_span': [first['start'], last['end']],
                          'inline_self_delimiting_children': sorted(emitted),
                          'original_array_item_count': len(node.children),
                          'whole_array_value_proved': False, 'whole_cell_parse_proved': False})


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cell', type=int, required=True)
    parser.add_argument('--raw', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--action', choices=['prepare', 'input', 'metadata', 'array-block'], required=True)
    parser.add_argument('--key', default='active8_enumeration')
    parser.add_argument('--block', type=int, default=0)
    parser.add_argument('--metadata-count', type=int, default=5)
    args = parser.parse_args(); engine = Engine(args.cell, args.raw, args.out)
    if args.action == 'prepare':
        result = engine.data_owner()
    elif args.action == 'input':
        result = engine.input_owner()
    elif args.action == 'metadata':
        result = engine.metadata_owner(args.metadata_count)
    else:
        result = engine.array_block_owner(args.key, args.block)
    print(json.dumps({k: result[k] for k in ['module', 'source', 'scope', 'planned_obligations']}, indent=2))
