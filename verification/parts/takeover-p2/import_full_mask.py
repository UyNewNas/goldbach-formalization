"""Lossless, pinned-source strip encoding of the full adopted paired mask.

This generates coordinates only.  It is not a numerical integral proof.
The encoded union has 186 strips; E0/E1 ownership labels and saved floors
remain in the pinned original witness and are not discarded analytically.
"""
from pathlib import Path
import collections, hashlib, json

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'verification/part2/data/corpus-renewal-paired-certificate-v2-20261010.json'
OUT = ROOT / 'ImbalancedChen/Certificates/PairedV2FullMaskData.lean'
raw = SOURCE.read_bytes()
assert hashlib.sha256(raw).hexdigest() == 'f6d31386f93cf77888ea4771ffa549a1cf61dca700bac618ff7646566a02f9b7'
source = json.loads(raw)
rows = source['rows']
assert len(rows) == 17572
grouped = collections.defaultdict(list)
for row in rows:
    grouped[row[1]].append(row[2])
assert sorted(grouped) == list(range(326,512))
first = []
for i in range(326,512):
    values = sorted(grouped[i])
    assert values == list(range(values[0],512))
    first.append(values[0])
encoded = [(i,j) for i,lo in zip(range(326,512),first) for j in range(lo,512)]
original = [(row[1],row[2]) for row in rows]
assert len(set(original)) == 17572
assert encoded == sorted(original)
assert sum(512-x for x in first) == 17572
stream = '\n'.join(f'{i},{j}' for i,j in encoded) + '\n'
text = '''import ImbalancedChen.Certificates.PairedV2GlobalGeometry
import Mathlib.Data.Fintype.Sigma

/-!
Lossless strip representation of all 17572 adopted paired-v2 grid pairs.
Source manuscript: ba6ec11d800eccc54406490631895e174de85766.
Source SHA256: f6d31386f93cf77888ea4771ffa549a1cf61dca700bac618ff7646566a02f9b7.
Generated by verification/parts/takeover-p2/import_full_mask.py.
The stream is sorted by actual grid pair, so its order differs from the
original E0-then-E1 witness. No numerical endpoint or saved floor is used.
-/

namespace ImbalancedChen.Certificates.PairedV2.FullMask

def firstU : Fin 186 → ℕ :=
  ![''' + ', '.join(map(str,first)) + ''']

end ImbalancedChen.Certificates.PairedV2.FullMask
'''
OUT.write_text(text,encoding='utf-8',newline='\n')
report = {'source_sha256':hashlib.sha256(raw).hexdigest(),
    'source_rows':len(rows),'strips':len(first),'decoded_rows':len(encoded),
    'lossless_permutation':True,'original_pairs_distinct':True,
    'sorted_pair_stream_sha256':hashlib.sha256(stream.encode()).hexdigest(),
    'generated_source_sha256':hashlib.sha256(text.encode()).hexdigest(),
    'scope':'Provenance check only; Lean must prove semantic ownership and integral bounds.'}
(Path(__file__).parent/'full-mask-import.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
