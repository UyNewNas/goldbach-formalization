"""Replay pinned, unedited Python VE excerpts and check Lean fixture literals.

Default execution is read-only. --refresh-fixtures updates numerical fixtures
and their Lean theorem block after an intentional source/case change. CI uses
only the default path. The full original scripts are optional for provenance
rechecking; no sieve table, integral calculation, or external package is run.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REFERENCE = HERE / "reference"
BOUNDARY = HERE / "VariableEnvelopeBoxesBoundary.lean"
FIXTURES = REFERENCE / "integer_fixtures.json"
BEGIN = "-- BEGIN GENERATED PYTHON REFERENCE FIXTURES"
END = "-- END GENERATED PYTHON REFERENCE FIXTURES"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def source_node(tree, name):
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return node
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return node
    raise AssertionError(f"Missing source node: {name}")


def check_provenance(source_dir):
    manifest = json.loads((REFERENCE / "source_manifest.json").read_text(encoding="utf-8"))
    for name, record in manifest["snapshots"].items():
        path = REFERENCE / name
        assert sha(path.read_bytes()) == record["sha256"], f"Changed snapshot: {name}"
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source)
        for fragment in record["excerpts"]:
            node = source_node(tree, fragment["name"])
            segment = ast.get_source_segment(source, node)
            assert sha(segment.encode("utf-8")) == fragment["sha256"], fragment
            if source_dir is not None:
                original = (source_dir / fragment["source"]).read_text(encoding="utf-8")
                old_node = source_node(ast.parse(original), fragment["name"])
                assert ast.get_source_segment(original, old_node) == segment, fragment
    if source_dir is not None:
        for name, record in manifest["sources"].items():
            assert sha((source_dir / name).read_bytes()) == record["sha256"], name
    return manifest


def run_reference(kind):
    ns = {"__name__": f"reference_{kind}"}
    source = REFERENCE / f"{kind}_prefix_ve.py"
    exec(compile(source.read_text(encoding="utf-8"), str(source), "exec"), ns)
    for out, value in (("NT", ns["THETA"] * ns["DEN"]), ("NMU", ns["MU"] * ns["DEN"])):
        assert value.denominator == 1
        ns[out] = value.numerator
    D, M, NT = ns["DEN"], ns["NMU"], ns["NT"]
    assert D == (16000 if kind == "variable" else 48000) * 2**24
    assert 128*M == 25*D
    intervals = {
        "peak_crossing": (M-1, M+1),
        "left_endpoint_peak": (M, M+1),
        "right_endpoint_peak": (M-1, M),
        "zero_width": (M+3, M+3),
        "negative_numerator": (D+1, D+5),
    }
    boxes = {
        "peak_crossing": (M//2-2, M//2+2, M//2-1, M//2+3, D//100, D//100+3),
        "zero_z": (D//10, D//8, D//20, 3*D//40, 0, 0),
        "sorting_crossing": (D//10, 3*D//20, 3*D//25, 4*D//25, D//100, D//50),
        "zero_width": (D//8+1, D//8+1, D//10+1, D//10+1, D//20+1, D//20+1),
        "empty_ordered": (0, D//10, D//5, D//4, 0, 0),
        "reversed_endpoints": (D//8, D//10, D//20, 3*D//40, 0, 0),
        "upper_x_is_mu": (M-2, M, M-4, M-1, 0, 1),
    }
    if kind == "variable":
        boxes["mu_diagonal"] = (M, M, M, M, M, M)
    interval_rows = []
    for name, (lo, hi) in intervals.items():
        interval_rows.append({"name": name, "lo": lo, "hi": hi,
                              "v_lo": ns["v_lo"](lo, hi), "v_hi": ns["v_hi"](lo, hi),
                              "point": hi, "v_point_hi": ns["v_point_hi"](hi)})
    box_rows = []
    for name, cell in boxes.items():
        if kind == "extended":
            # Enforce the actual old-code dispatch condition, including strict x0<M.
            assert cell[0] < M and cell[1] <= M
        box_rows.append({"name": name, "cell": list(cell), "phi_range": list(ns["phi_range"](cell))})
    return {"kind": kind, "DEN": D, "NMU": M, "NT": NT, "theta": str(ns["THETA"]),
            "intervals": interval_rows, "boxes": box_rows}


def lean_int(n):
    return f"({n})" if n < 0 else str(n)


def lean_block(data):
    lines = [BEGIN, "-- Generated by check_variable_envelope_reference.py; no floating-point arithmetic."]
    for record in data:
        kind, D, M, NT = record["kind"], record["DEN"], record["NMU"], record["NT"]
        base = 16000 if kind == "variable" else 48000
        tn, td = record["theta"].split("/")
        lines += [f"theorem {kind}_actual_scale :",
                  f"    ({D} : ℤ) = {base} * 2^24 ∧ 128*({M} : ℤ) = 25*{D} ∧",
                  f"    ({NT} : ℚ) / {D} = {tn}/{td} := by norm_num", ""]
        for row in record["intervals"]:
            name = f"{kind}_{row['name']}_scalar"
            lines += [f"theorem {name} :",
                      f"    scaledVLo {D} {lean_int(row['lo'])} {lean_int(row['hi'])} = {lean_int(row['v_lo'])} ∧",
                      f"    scaledVHi {D} {M} {lean_int(row['lo'])} {lean_int(row['hi'])} = {lean_int(row['v_hi'])} ∧",
                      f"    scaledVPointHi {D} {lean_int(row['point'])} = {lean_int(row['v_point_hi'])} := by",
                      "  norm_num [scaledVLo, scaledVHi, scaledVPointHi, ceilDiv]", ""]
        for row in record["boxes"]:
            cell = ", ".join(lean_int(n) for n in row["cell"])
            lo, hi = row["phi_range"]
            lines += [f"theorem {kind}_{row['name']}_phi :",
                      f"    ScaledBox.phiRange {D} {M} {NT}",
                      f"      ⟨{cell}⟩ = ({lean_int(lo)}, {lean_int(hi)}) := by",
                      "  norm_num [ScaledBox.phiRange, ScaledBox.rawLower, ScaledBox.rawUpper,",
                      "    scaledVLo, scaledVHi, scaledVPointHi, scaledBLo, scaledBHi, ceilDiv]", ""]
    lines.append(END)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, help="Optionally verify the full original source byte hashes.")
    parser.add_argument("--refresh-fixtures", action="store_true")
    args = parser.parse_args()
    manifest = check_provenance(args.source_dir)
    data = [run_reference(kind) for kind in ("variable", "extended")]
    block = lean_block(data)
    source = BOUNDARY.read_text(encoding="utf-8")
    start, end = source.index(BEGIN), source.index(END) + len(END)
    if args.refresh_fixtures:
        FIXTURES.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
        BOUNDARY.write_text(source[:start] + block + source[end:], encoding="utf-8", newline="\n")
    else:
        assert json.loads(FIXTURES.read_text(encoding="utf-8")) == data, "Numerical reference fixtures changed"
        assert source[start:end] == block, "Lean reference theorem block is stale or modified"
    print(json.dumps({
        "status": "PASS", "scope": "VE only; extended x0<NMU and x1<=NMU",
        "original_sources_checked": args.source_dir is not None,
        "original_sha256": {n: r["sha256"] for n, r in manifest["sources"].items()},
        "interval_cases": sum(len(r["intervals"]) for r in data),
        "phi_range_cases": sum(len(r["boxes"]) for r in data),
        "fixtures": data,
    }, indent=2))


if __name__ == "__main__":
    main()
